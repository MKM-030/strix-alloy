namespace halogen_nohit::owner_capture {

// These authorities are intentionally unimplemented. Only the separately
// reviewed engine integration may define them and issue the capabilities below.
// This adapter neither installs their observations nor proves native lifetime.
class NativeReadBoundary;
class PrefixAcknowledgementAuthority;

struct ReadIntervalBinding {
    handoff::Id interval_id{}; // Private owner-issued value, never an address hash.
    std::uint64_t invocation_sequence{}; // Assigned before the seam; never reused.
    bool operator==(const ReadIntervalBinding&) const = default;
};

// Actual native read spans, valid only within NativeReadInterval. No origins are
// converted back into pointers. The upstream boundary supplies held spans after
// establishing release/mutation exclusion, including the exact vector suffix.
struct NativeReadSpans {
    std::span<const std::uint8_t> request{}, model{}, record{}, outer{}, suffix{};
};

// A nontransferable scoped upstream assertion, not a proof generated by this
// code. Its issuer must independently hold every span alive and coherent through
// observe(), exclude reset/slot/worker mutation, and serialize this handler.
// Registers must be the real seam image. Definitions are immutable owned trusted
// tokenizer data held for the call. If observed_owner is supplied, its successful
// birth, epoch/generations and loaded model/tokenizer were independently observed.
// Neither span validation nor a pre/post generation comparison grants this scope.
class NativeReadInterval {
public:
    NativeReadInterval(const NativeReadInterval&) = delete;
    NativeReadInterval& operator=(const NativeReadInterval&) = delete;
    NativeReadInterval(NativeReadInterval&&) = delete;
    NativeReadInterval& operator=(NativeReadInterval&&) = delete;
private:
    friend class NativeReadBoundary;
    friend class NativeOwnerCapture;
    NativeReadInterval(ReadIntervalBinding binding, NativeReadSpans spans,
                       frame_relay::RegisterImage registers,
                       const TokenDefinitions* definitions,
                       const handoff::OwnerIdentity* observed_owner) noexcept
        : binding_(binding), spans_(spans), registers_(registers),
          definitions_(definitions), observed_owner_(observed_owner) {}
    const ReadIntervalBinding binding_;
    const NativeReadSpans spans_;
    const frame_relay::RegisterImage registers_;
    const TokenDefinitions* const definitions_;
    const handoff::OwnerIdentity* const observed_owner_;
};

// Engine-local binding of a PREVIOUSLY completed acknowledgement. The complete
// vector lives in separate immutable preallocated seed storage. Its authority
// must have verified every owned ID and the complete fingerprint outside the
// seam, and independently proved continuity to this exact future read interval.
// A matching length/suffix/fingerprint label alone does not establish continuity.
struct PriorPrefixBinding {
    ReadIntervalBinding read_interval{};
    handoff::Frontier canonical{};
    handoff::Id first_round_id{}; // Required only for a qualified first seed.
    std::int32_t native_slot{}; // Independently acknowledged slot, not a generation.
    const TokenDefinitions* definitions{};
    std::span<const std::int32_t> complete_owned_prefix{};
    std::uint64_t request_origin{}, model_origin{}, record_origin{}, outer_origin{};
    std::uint64_t vector_begin{}, vector_end{}, vector_capacity{};
};

// No public constructor: the seam adapter cannot turn decoded facts, booleans or
// a suffix digest into a full-prefix acknowledgement. The external authority
// issues this only after acknowledgement completes BEFORE the bound invocation.
// All referenced owned data must remain immutable and alive through observe().
class PriorPrefixAcknowledgement {
public:
    PriorPrefixAcknowledgement(const PriorPrefixAcknowledgement&) = delete;
    PriorPrefixAcknowledgement& operator=(const PriorPrefixAcknowledgement&) = delete;
    PriorPrefixAcknowledgement(PriorPrefixAcknowledgement&&) = delete;
    PriorPrefixAcknowledgement& operator=(PriorPrefixAcknowledgement&&) = delete;
private:
    friend class PrefixAcknowledgementAuthority;
    friend class NativeOwnerCapture;
    explicit PriorPrefixAcknowledgement(const PriorPrefixBinding& binding) noexcept
        : binding_(binding) {}
    const PriorPrefixBinding binding_;
};

enum class ObservationResult : std::uint8_t {
    Disabled, ReadIntervalUnavailable, InvalidReadSpans, DecodeRejected,
    OwnedUnqualified, PrefixBindingMismatch, HandoffUnavailable, ObservedStock
};

// Value-only publication. Decoded facts describe an owned observation, not an
// authoritative outcome or an acknowledgement. No native pointers/registers,
// copy descriptors, native stack views or read capabilities escape here.
struct OwnedObservation {
    ObservationResult result = ObservationResult::Disabled;
    capture::DecodeResult decode_result = capture::DecodeResult::MissingCopy;
    bool facts_available = false;
    capture::NoHitFacts facts{};
    bool handoff_consumed = false;
    Decision stock_decision{kStockResumeRva, Reason::Disabled, 0, false};
};

inline constexpr std::size_t kOwnedNativeBytes = capture::kRequestBytes +
    capture::kModelBytes + capture::kRecordBytes + capture::kOuterBytes +
    kMaxWindowTokens * sizeof(std::int32_t);
static_assert(kOwnedNativeBytes == 6018);

// Preallocate once per exclusively owned handler; no per-invocation allocation.
// This is a SEPARATE native-read entry, never halogen_nohit_frame_observer.
// The frozen relay observer ABI still permits only owned register/XSAVE views.
class NativeOwnerCapture {
public:
    explicit NativeOwnerCapture(bool enable = false) noexcept : enabled_(enable) {}
    NativeOwnerCapture(const NativeOwnerCapture&) = delete;
    NativeOwnerCapture& operator=(const NativeOwnerCapture&) = delete;
    NativeOwnerCapture(NativeOwnerCapture&&) = delete;
    NativeOwnerCapture& operator=(NativeOwnerCapture&&) = delete;

    // Caller exclusively owns adapter AND handoff for the entire call. nullptr
    // read => no native reads. Missing acknowledgement => owned observation only;
    // never initialize an unqualified seed. A previously live feed is retired on
    // lost proof or failed capture. Disabled mode changes no handoff state.
    OwnedObservation observe(const NativeReadInterval* read,
                             const PriorPrefixAcknowledgement* acknowledged,
                             handoff::NativeOutcomeHandoff& handoff) noexcept;
private:
    bool enabled_ = false;
    std::array<std::uint8_t, capture::kRequestBytes> request_{};
    std::array<std::uint8_t, capture::kModelBytes> model_{};
    std::array<std::uint8_t, capture::kRecordBytes> record_{};
    std::array<std::uint8_t, capture::kOuterBytes> outer_{};
    std::array<std::int32_t, kMaxWindowTokens> suffix_{};
    // Work buffers are preallocated too. Synthetic SavedFrame is only a local
    // projection; real relay XSAVE remains the sole native restoration image.
    OwnedObservation observation_{};
    handoff::SeedCopy seed_{};
    handoff::SeamCapture seam_{};
    SavedFrame projected_{};
};

} // namespace halogen_nohit::owner_capture
